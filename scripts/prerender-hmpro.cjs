// Generate first-load HTML with the approved browser renderer and data.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const assets=path.join(root,'public/dongfunda-assets/r04/hmpro');
const original=fs.readFileSync(path.join(root,'lib/dongfunda/approved-public/hmpro-template.html'),'utf8');
const support=JSON.parse(fs.readFileSync(path.join(root,'lib/dongfunda/dashboard-support.json'),'utf8')).html;
const rows=JSON.parse(fs.readFileSync(path.join(root,'lib/dongfunda/hmpro-one-report.json'),'utf8'));
fs.writeFileSync(path.join(assets,'data.js'),'window.HMPRO_DATA = '+JSON.stringify(rows)+';\n');
const nodes=new Map();
function node(id){if(!nodes.has(id))nodes.set(id,{innerHTML:'',textContent:'',addEventListener(){}});return nodes.get(id);}
const context=vm.createContext({window:{},URLSearchParams,location:{search:''},document:{
 getElementById:node,
 querySelectorAll(selector){if(selector==='[data-year]')return [];if(selector==='.selected-label')return [node('selected-period-label')];throw Error('Unknown HMPRO selector: '+selector);}
}});
for(const file of ['data.js','dashboard.js'])vm.runInContext(fs.readFileSync(path.join(assets,file),'utf8'),context,{timeout:3000,filename:file});
const escape=value=>String(value).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
let html=original.replace('<!-- DONGFUNDA_DASHBOARD_SUPPORT -->',support);
for(const [id,value]of nodes){
 const content=value.innerHTML||(value.textContent?escape(value.textContent):'');if(!content)continue;
 const pattern=new RegExp(`(<[a-z][^>]*\\bid="${id}"[^>]*>)\\s*(</[a-z][^>]*>)`);
 if(!pattern.test(html))throw Error('Missing HMPRO prerender container: '+id);
 html=html.replace(pattern,(_,open,close)=>open+content+close);
}
for(const expected of ['70,569.77','65,955.18','6,011.39','114','133','2564','2568'])if(!html.includes(expected))throw Error('Missing HMPRO content: '+expected);
if(/LOCAL MOCKUP|noindex|localhost|127\.0\.0\.1/.test(html))throw Error('Preview-only content in HMPRO public page');
fs.writeFileSync(path.join(root,'lib/dongfunda/approved-public/hmpro-rendered.ts'),'// Generated by scripts/prerender-hmpro.cjs from the shared browser renderer.\nexport const hmproHtml = '+JSON.stringify(html)+';\n');
console.log('HMPRO first-load HTML generated from the approved five-year renderer.');
