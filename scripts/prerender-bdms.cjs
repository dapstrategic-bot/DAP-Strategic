// Generate first-load HTML from the exact same approved renderer/data as the
// interactive browser. Runs at build time only; no separate financial dataset.
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const templateSource = fs.readFileSync(path.join(root, 'lib/dongfunda/approved-public/templates.ts'), 'utf8');
const templates = JSON.parse(templateSource.split('export const templates = ')[1].replace(/ as const;\s*$/, ''));
const original = templates.bdms;
const nodes = new Map();
const context = vm.createContext({
  window: {}, URLSearchParams, location: {search: ''},
  document: {
    title: '',
    querySelectorAll(selector) {
      if (selector === '[data-pipeline-filter]') return [];
      throw Error(`Unsupported build-time selector: ${selector}`);
    },
    getElementById(id) {
      if (id !== 'approved-public-content' && !original.includes(`id="${id}"`)) throw Error(`Unknown dashboard node: ${id}`);
      if (!nodes.has(id)) nodes.set(id, {innerHTML:'',textContent:'',checked:false,addEventListener(){}});
      return nodes.get(id);
    },
  },
});
for (const file of ['data.js','dashboard.js']) {
  vm.runInContext(fs.readFileSync(path.join(root,'public/dongfunda-assets/r04/bdms',file),'utf8'),context,{timeout:3000,filename:file});
}
const escape = value => String(value).replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
let html = original;
for (const [id,node] of nodes) {
  const content=node.innerHTML || (node.textContent ? escape(node.textContent) : '');
  if (!content) continue;
  // Populate empty approved containers only. No extra SEO-only hidden content.
  const pattern = new RegExp(`(<[a-z][^>]*\\bid="${id}"[^>]*>)\\s*(</[a-z][^>]*>)`);
  html=html.replace(pattern,(_,open,close)=>open+content+close);
}
for (const value of ['113,272.5','9,345','107,513.7','Bangkok Proton Center']) {
  if (!html.includes(value)) throw Error(`Missing server-rendered content: ${value}`);
}
fs.writeFileSync(path.join(root,'lib/dongfunda/approved-public/bdms-rendered.ts'),
  '// Generated by scripts/prerender-bdms.cjs; edit the shared renderer/data instead.\nexport const bdmsHtml = '+JSON.stringify(html)+';\n');
console.log('BDMS first-load HTML generated from shared approved renderer.');
